/**
 * Theme File Generator
 *
 * Generates TypeScript theme files in LottieThemeConfig format
 */

import type { GeneratedTheme, ThemeGenerationResult } from "./types"

/**
 * Generate TypeScript file content for a single theme
 */
export function generateThemeFileContent(
  animationName: string,
  theme: GeneratedTheme,
): string {
  const { themeId, name, description, palette, colors, skippedElements } = theme

  // Format colors object with proper indentation
  const colorsEntries = Object.entries(colors)
    .map(([key, value]) => `    ${key}: "${value}",`)
    .join("\n")

  // Format skipped elements array
  const skippedStr =
    skippedElements.length > 0
      ? `[\n    "${skippedElements.join('",\n    "')}",\n  ]`
      : "[]"

  return `import type { LottieThemeConfig } from "../../../../theming/lottieColorMapping"

export const ${camelCase(themeId.replace(/-/g, "_"))}Theme: LottieThemeConfig = {
  themeId: "${themeId}",
  name: "${name}",
  description: "${description}",
  baseColor: "${palette.baseColor}",
  mode: "${palette.mode}",
  colors: {
${colorsEntries}
  },
  skippedElements: ${skippedStr},
}
`
}

/**
 * Generate a single consolidated themes file with all themes as named exports
 * This is the preferred export format - one file with all themes
 */
export function generateConsolidatedThemesFile(
  animationName: string,
  result: ThemeGenerationResult,
): string {
  const themes = result.themes

  // Generate theme objects for all themes
  const themeExports = themes.map((theme) => {
    const { themeId, name, description, palette, colors, skippedElements } =
      theme
    const constName = `${camelCase(themeId.replace(/-/g, "_"))}Theme`

    // Format colors object with proper indentation
    const colorsEntries = Object.entries(colors)
      .map(([key, value]) => `    ${key}: "${value}",`)
      .join("\n")

    // Format skipped elements array
    const skippedStr =
      skippedElements.length > 0
        ? `[\n    "${skippedElements.join('",\n    "')}",\n  ]`
        : "[]"

    return `export const ${constName}: LottieThemeConfig = {
  themeId: "${themeId}",
  name: "${name}",
  description: "${escapeString(description)}",
  baseColor: "${palette.baseColor}",
  mode: "${palette.mode}",
  colors: {
${colorsEntries}
  },
  skippedElements: ${skippedStr},
}`
  })

  // Generate list of theme constant names for the allThemes array
  const themeNames = themes.map(
    (theme) => `${camelCase(theme.themeId.replace(/-/g, "_"))}Theme`,
  )

  return `/**
 * ${animationName} Theme Configurations
 * Generated by Lottie Naming Tool
 *
 * Variant: ${result.variant}
 * Total themes: ${themes.length}
 */

import type { LottieThemeConfig } from "../../theming/lottieColorMapping"

${themeExports.join("\n\n")}

/**
 * All themes for this animation
 */
export const allThemes: LottieThemeConfig[] = [
  ${themeNames.join(",\n  ")},
]

/**
 * Theme lookup by ID
 */
export const themesById: Record<string, LottieThemeConfig> = {
  ${themeNames.map((name) => `"${themes[themeNames.indexOf(name)].themeId}": ${name}`).join(",\n  ")},
}
`
}

/**
 * Escape string for use in template literals
 */
function escapeString(str: string): string {
  return str.replace(/\\/g, "\\\\").replace(/"/g, '\\"')
}

/**
 * Generate filename for a theme file
 */
export function generateThemeFilename(palette: { id: string }): string {
  return `${palette.id}.ts`
}

/**
 * Generate all theme files for an animation
 */
export function generateAllThemeFiles(
  result: ThemeGenerationResult,
): Array<{ filename: string; content: string; subdirectory: string }> {
  const files: Array<{
    filename: string
    content: string
    subdirectory: string
  }> = []

  for (const theme of result.themes) {
    const filename = generateThemeFilename(theme.palette)
    const content = generateThemeFileContent(result.animationName, theme)
    // Include animation name in path for organization
    const subdirectory = `themes/${result.animationName}/${result.variant}`

    files.push({ filename, content, subdirectory })
  }

  return files
}

