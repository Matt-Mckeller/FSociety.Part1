/**
 * Generate registry entry code snippet for lottieThemeRegistry.ts
 * @deprecated Use generateAnimationThemesFile instead for auto-registration
 */
export function generateRegistryEntrySnippet(
  animationName: string,
  variants: string[],
  themesPerVariant: Record<string, string[]>,
): string {
  const variantEntries = variants
    .map((variant) => {
      const themes = themesPerVariant[variant] || []
      const themesList =
        themes.length > 0 ? `["${themes.join('", "')}"]` : "UNIVERSAL_THEMES"
      return `    { variant: "${variant}", themes: ${themesList} },`
    })
    .join("\n")

  return `// Add this to ANIMATION_THEME_SUPPORT array in lottieThemeRegistry.ts:
createAnimationSupport("${animationName}", [
${variantEntries}
]),`
}

/**
 * Convert string to camelCase
 */
function camelCase(str: string): string {
  return str
    .split(/[_-]/)
    .map((word, index) =>
      index === 0
        ? word.toLowerCase()
        : word.charAt(0).toUpperCase() + word.slice(1).toLowerCase(),
    )
    .join("")
}

/**
 * Generate index file for themes directory
 */
export function generateThemeIndexContent(themes: GeneratedTheme[]): string {
  const imports = themes
    .map((t) => {
      const varName = camelCase(t.themeId.replace(/-/g, "_"))
      const filename = t.palette.id
      return `export { default as ${varName}Theme } from "./${filename}"`
    })
    .join("\n")

  return `/**
 * Theme exports for this animation
 * Auto-generated by Lottie Naming Tool
 */

${imports}
`
}

/**
 * Generate a .themes.ts file for auto-registration in theming/animations/
 *
 * This file is automatically discovered by lottieThemeRegistry.ts
 */
export function generateAnimationThemesFileContent(
  animationName: string,
  variants: string[],
  themesPerVariant: Record<string, string[]>,
): string {
  // Collect all unique theme IDs across variants
  const allThemes = new Set<string>()
  for (const themes of Object.values(themesPerVariant)) {
    themes.forEach((t) => allThemes.add(t))
  }

  // Check if using universal themes (all standard themes)
  const universalThemes = [
    "purple-light",
    "purple-dark",
    "blue-light",
    "blue-dark",
    "green-light",
    "green-dark",
    "orange-light",
    "orange-dark",
    "red-light",
    "red-dark",
    "teal-light",
    "teal-dark",
  ]
  const isUsingUniversal = universalThemes.every((t) => allThemes.has(t))

  // Build variant entries
  const variantEntries = variants
    .map((variant) => {
      const themes = themesPerVariant[variant] || []
      if (isUsingUniversal && themes.length === universalThemes.length) {
        return `  { variant: "${variant}", themes: UNIVERSAL_THEMES },`
      }
      return `  { variant: "${variant}", themes: ["${themes.join('", "')}"] },`
    })
    .join("\n")

  return `/**
 * ${animationName} Theme Support
 * Auto-registered via animations/index.ts
 * Generated by Lottie Naming Tool
 */

import type { VariantThemeSupport } from "../lottieThemeRegistry"

${
  isUsingUniversal
    ? `// Universal themes - matches THEME_REGISTRY universal themes
const UNIVERSAL_THEMES = [
  "purple-light",
  "purple-dark",
  "blue-light",
  "blue-dark",
  "green-light",
  "green-dark",
  "orange-light",
  "orange-dark",
  "red-light",
  "red-dark",
  "teal-light",
  "teal-dark",
]

`
    : ""
}export const animationName = "${animationName}"

export const variantThemes: VariantThemeSupport[] = [
${variantEntries}
]
`
}

/**
 * Get the filename for an animation's .themes.ts file
 */
export function getAnimationThemesFilename(animationName: string): string {
  return `${animationName}.themes.ts`
}
